//////////////////////////////////////////////////////////////////////////////////
// LCD硬件抽象层头文件
// 提供平台无关的LCD硬件接口抽象
// 支持动态注册不同平台的硬件实现
//////////////////////////////////////////////////////////////////////////////////

#ifndef __LCD_HAL_H
#define __LCD_HAL_H

#include "stdint.h"
#include "lcd.h"
#include "GUI_HAL.h"

#ifndef u8
#define u8 uint8_t
#endif

#ifndef u16
#define u16 uint16_t
#endif

#ifndef u32
#define u32 uint32_t
#endif

/* --------------------------------- 此处修改HAL接口结构体定义 -------------------------------- */
/** ***************************************************************************
 * @brief  LCD硬件抽象层接口结构体
 * @note   包含所有需要平台相关实现的硬件操作函数指针
 *****************************************************************************/
typedef struct
{
    // GPIO控制函数
    void (*GPIO_CS_Set)(void); // CS引脚置高
    void (*GPIO_CS_Clr)(void); // CS引脚置低
    void (*GPIO_DC_Set)(void); // DC引脚置高 (数据模式)
    void (*GPIO_DC_Clr)(void); // DC引脚置低 (命令模式)

    // 可选功能的GPIO控制函数
    void (*GPIO_RST_Set)(void); // RST引脚置高 (非复位状态)
    void (*GPIO_RST_Clr)(void); // RST引脚置低 (复位状态)
    void (*GPIO_BLK_Set)(void); // 背光引脚置高 (开启背光)
    void (*GPIO_BLK_Clr)(void); // 背光引脚置低 (关闭背光)

    // SPI通信函数
    u8 (*SPI_Write_Byte)(u8 data); // SPI写入一个字节数据

    // 延时函数
    void (*Delay_Ms)(u32 ms); // 毫秒延时函数

    // SPI速度设置函数 (可选)
    void (*SPI_Set_Speed)(u8 speed); // 设置SPI速度，0-高速，1-低速

    // SPI初始化函数 (可选)
    void (*SPI_Init)(void);       // SPI初始化函数
    void (*SPI_MSP_Init)(void);   // SPI MSP初始化函数
    void (*SPI_MSP_DeInit)(void); // SPI MSP反初始化函数

} LCD_HAL_t;
/* 自定义部分结束 */

/** ***************************************************************************
 * @brief  注册LCD硬件抽象层实现
 * @param  hal: 指向硬件抽象层实现结构体的指针
 * @retval None
 *****************************************************************************/
void LCD_HAL_Register(const LCD_HAL_t *hal);

/* --------------------------------- 此处修改HAL封装函数声明 -------------------------------- */
/** ***************************************************************************
 * @brief  LCD HAL层CS引脚控制函数
 * @retval None
 *****************************************************************************/
void LCD_HAL_CS_SET(void);
void LCD_HAL_CS_CLR(void);

/** ***************************************************************************
 * @brief  LCD HAL层DC引脚控制函数
 * @retval None
 *****************************************************************************/
void LCD_HAL_DC_SET(void);
void LCD_HAL_DC_CLR(void);

/** ***************************************************************************
 * @brief  LCD HAL层RST引脚控制函数
 * @retval None
 *****************************************************************************/
void LCD_HAL_RST_SET(void);
void LCD_HAL_RST_CLR(void);

/** ***************************************************************************
 * @brief  LCD HAL层背光控制函数
 * @retval None
 *****************************************************************************/
void LCD_HAL_BLK_SET(void);
void LCD_HAL_BLK_CLR(void);

/** ***************************************************************************
 * @brief  LCD HAL层SPI通信函数
 * @param  data: 要发送的数据
 * @retval 接收到的数据
 *****************************************************************************/
u8 LCD_HAL_SPI_WRITE_BYTE(u8 data);

/** ***************************************************************************
 * @brief  LCD HAL层延时函数
 * @param  ms: 延时毫秒数
 * @retval None
 *****************************************************************************/
void LCD_HAL_DELAY_MS(u32 ms);

/** ***************************************************************************
 * @brief  LCD HAL层SPI速度设置函数
 * @param  speed: SPI速度设置，0-高速，1-低速
 * @retval None
 *****************************************************************************/
void LCD_HAL_SPI_SET_SPEED(u8 speed);

/** ***************************************************************************
 * @brief  LCD HAL层SPI初始化函数
 * @retval None
 *****************************************************************************/
void LCD_HAL_SPI_INIT(void);

/** ***************************************************************************
 * @brief  LCD HAL层SPI MSP初始化函数
 * @retval None
 *****************************************************************************/
void LCD_HAL_SPI_MSP_INIT(void);

/** ***************************************************************************
 * @brief  LCD HAL层SPI MSP反初始化函数
 * @retval None
 *****************************************************************************/
void LCD_HAL_SPI_MSP_DEINIT(void);

/** ***************************************************************************
 * @brief  初始化STM32平台LCD硬件抽象层
 * @retval None
 * @note   在系统初始化时调用此函数进行HAL层注册
 *****************************************************************************/
void STM32_LCD_HAL_Init(void);
/* 自定义部分结束 */

#endif /* __LCD_HAL_H */
